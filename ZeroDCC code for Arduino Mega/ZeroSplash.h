void drawZeroSplash(Adafruit_GFX &tft) {
  tft.setRotation(ZS_ROT);
  tft.fillScreen(ZS_PALETTE[0]);

  int16_t x = 0, y = 0;
  for (uint16_t i = 0; i < ZS_RUNS_LEN; i++) {
    uint8_t b   = pgm_read_byte(&ZS_RUNS[i]);
    uint8_t c   = b >> 5;
    uint8_t len = (b & 0x1F) + 1;
    if (c) tft.drawFastHLine(ZS_X0 + x, ZS_Y0 + y, len, ZS_PALETTE[c]);
    x += len;
    if (x >= ZS_W) { x = 0; y++; }
  }
}
